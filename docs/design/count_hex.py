import os
import re

pattern = re.compile(r'#[0-9a-fA-F]{3,6}\b')

token_files = ['frontend/src/design-system.css', 'frontend/src/index.css']

token_counts = {}
comp_counts = {}
token_total = 0
comp_total = 0

for root, _, files in os.walk('d:/Important/00-Projects/QueryTrustAI/frontend/src'):
    for f in files:
        if f.endswith(('.tsx', '.ts', '.css')):
            p = os.path.join(root, f)
            rel = os.path.relpath(p, 'd:/Important/00-Projects/QueryTrustAI').replace('\\', '/')
            with open(p, 'r', encoding='utf-8', errors='ignore') as fp:
                matches = pattern.findall(fp.read())
                c = len(matches)
                if c > 0:
                    if rel in token_files:
                        token_counts[rel] = c
                        token_total += c
                    else:
                        comp_counts[rel] = c
                        comp_total += c

total_all = token_total + comp_total

report = []
report.append(f"# Exact Hex Color Literal Inventory\n")
report.append(f"Generated by `docs/design/count_hex.py`.\n\n")
report.append(f"- **Total Hex Occurrences across codebase**: **{total_all}**\n")
report.append(f"- **1. Token Definition Files (Legitimate token layer)**: **{token_total}**\n")
report.append(f"- **2. Hardcoded in Components / CSS (The problem to resolve)**: **{comp_total}**\n\n")

report.append("### 1. Token Definition Files\n")
report.append("| File Path | Hex Count |\n|---|---|\n")
for f, c in sorted(token_counts.items(), key=lambda x: -x[1]):
    report.append(f"| `{f}` | {c} |\n")
report.append(f"| **Subtotal (Token Layer)** | **{token_total}** |\n\n")

report.append("### 2. Hardcoded in Components & Component CSS (Violations)\n")
report.append("| File Path | Hex Count |\n|---|---|\n")
for f, c in sorted(comp_counts.items(), key=lambda x: -x[1]):
    report.append(f"| `{f}` | {c} |\n")
report.append(f"| **Subtotal (Components)** | **{comp_total}** |\n\n")

report.append(f"**Verification Check**: {token_total} (Tokens) + {comp_total} (Components) = **{total_all}** (Exact Total)\n")

text = "".join(report)
print(text)
with open('d:/Important/00-Projects/QueryTrustAI/docs/design/hex_inventory.md', 'w', encoding='utf-8') as fp:
    fp.write(text)
